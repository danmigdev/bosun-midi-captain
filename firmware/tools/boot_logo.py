"""Generate firmware/src/boot_logo.c, the built-in TFT startup logo.

The Bosun icon is scaled to 176x176 (LANCZOS), composited on black and stored
as per-row runs of RGB565 pixels for the (32, 12) square of the 240x200 logo
box. Runs never cross rows, so the firmware decodes row by row. The output is
committed; regenerate it only when the icon changes. Requires Pillow.

    python firmware/tools/boot_logo.py           # rewrite the C file
    python firmware/tools/boot_logo.py --check   # fail if it is out of date
"""
import argparse
import hashlib
from pathlib import Path
import sys

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
ICON = ROOT / "editor/src-tauri/icons/icon.png"
OUTPUT = ROOT / "firmware/src/boot_logo.c"
SIZE, X, Y = 176, 32, 12


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def runs(image):
    pixels = image.load()
    result = []
    for y in range(SIZE):
        row = [rgb565(*pixels[x, y]) for x in range(SIZE)]
        start = 0
        for x in range(1, SIZE + 1):
            if x == SIZE or row[x] != row[start]:
                result.append((x - start, row[start]))
                start = x
    return result


def generate():
    source = ICON.read_bytes()
    icon = Image.open(ICON).convert("RGBA").resize((SIZE, SIZE), Image.Resampling.LANCZOS)
    image = Image.alpha_composite(Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 255)), icon).convert("RGB")
    encoded = runs(image)
    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-or-later */",
        "/* Generated by firmware/tools/boot_logo.py from editor/src-tauri/icons/icon.png",
        f" * (sha256 {hashlib.sha256(source).hexdigest()}); do not edit.",
        " * Built-in startup logo: the icon scaled to 176x176 on black, at (32, 12)",
        " * of the 240x200 logo box. Runs are {length, RGB565} and never cross rows. */",
        f"enum {{ BOOT_LOGO_X = {X}, BOOT_LOGO_Y = {Y}, BOOT_LOGO_SIZE = {SIZE}, BOOT_LOGO_RUNS = {len(encoded)} }};",
        "static const uint16_t boot_logo_runs[BOOT_LOGO_RUNS][2] = {",
    ]
    for i in range(0, len(encoded), 8):
        lines.append("    " + ",".join(f"{{{n},0x{c:04x}}}" for n, c in encoded[i:i + 8]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    args = parser.parse_args()
    text = generate()
    if args.check:
        current = OUTPUT.read_text(encoding="ascii") if OUTPUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            sys.exit(f"{OUTPUT} is out of date; run {Path(__file__).name}")
    else:
        OUTPUT.write_text(text, encoding="ascii", newline="\n")
